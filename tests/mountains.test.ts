import { it, expect } from "vitest";
import { emptySnapshot } from "../lib/domain";
import { transition } from "../lib/actions";
import { mountainDetails } from "../lib/mountains";
it("mountain browsing derives only its own saved context and earned history without mutation", () => {
  let s = transition(emptySnapshot(), { type: "create", title: "A", finishCondition: "Checked A", action: "Draw A", minutes: 3 }, 10000);
  const a = s.mountains[0].id;
  s = transition(s, { type: "complete" }, 11000);
  s = transition(s, { type: "create", title: "B", finishCondition: "Checked B", action: "Draw B", minutes: 4 }, 12000);
  s = transition(s, { type: "start", minutes: 4 }, 12000);
  s = transition(s, { type: "note", note: "B only" }, 13000);
  s = transition(s, { type: "save" }, 14000);
  const before = structuredClone(s);
  expect(mountainDetails(s, a)).toMatchObject({ saved: undefined, pending: true, status: "All actions done · goal unconfirmed" });
  expect(mountainDetails(s, s.mountains[1].id).saved?.note).toBe("B only");
  expect(s).toEqual(before);
});
it("prioritizes the mountain's latest explicit save over an older action's later start", () => {
  let s = transition(emptySnapshot(), { type: "create", title: "A", finishCondition: "Checked A", action: "Draw A", minutes: 3 }, 10000);
  const first = s.subtasks[0];
  const second = { ...first, id: crypto.randomUUID(), title: "Check A", orderKey: 1, checkpointSlot: s.mountains[0].nextCheckpointSlot++ };
  s.subtasks.push(second);
  s = transition(s, { type: "start", minutes: 3 }, 10000);
  s = transition(s, { type: "save" }, 11000);
  s = transition(s, { type: "select", id: second.id }, 12000);
  s = transition(s, { type: "start", minutes: 3 }, 12000);
  s = transition(s, { type: "save" }, 13000);
  s = transition(s, { type: "select", id: first.id }, 14000);
  s = transition(s, { type: "save" }, 15000);
  expect(mountainDetails(s, first.mountainId).saved?.subtaskId).toBe(first.id);
  expect(mountainDetails(s, first.mountainId).next?.id).toBe(first.id);
});
