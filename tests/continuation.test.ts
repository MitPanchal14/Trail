import { it, expect } from "vitest";
import { transition } from "../lib/actions";
import { emptySnapshot, currentSession } from "../lib/domain";
import { earnedPosition } from "../lib/trail-position";
import { climberPosition, checkpointPosition } from "../lib/terrain";
it("starts a validated target atomically and reconstructs chronological noncontiguous positions", () => {
  let s = transition(emptySnapshot(), { type: "create", title: "Fictional guide", finishCondition: "Checked", action: "First", minutes: 2 });
  const first = s.subtasks[0];
  const second = { ...first, id: crypto.randomUUID(), title: "Second", checkpointSlot: 7, orderKey: -1, suggestedMinutes: 9 };
  s.subtasks.push(second); s.mountains[0].nextCheckpointSlot = 8;
  expect(earnedPosition(s, first.mountainId)).toBeNull();
  expect(climberPosition(null)).not.toEqual(climberPosition(0));
  expect(() => transition(s, { type: "start-next", id: second.id, minutes: 0 })).toThrow();
  expect(s.sessions).toHaveLength(0);
  s = transition(s, { type: "start-next", id: second.id, minutes: 9 }, 100000);
  expect(currentSession(s)?.remainingMs).toBe(540000);
  expect(transition(s, { type: "start-next", id: first.id, minutes: 2 })).toBe(s);
  s = transition(s, { type: "complete" }, 101000);
  expect(earnedPosition(s, first.mountainId)).toBe(7);
  const savedPosition = earnedPosition(s, first.mountainId);
  for (const type of ["save", "pause", "tick"] as const) {
    s = transition(s, { type });
    expect(earnedPosition(s, first.mountainId)).toBe(savedPosition);
  }
  s = transition(s, { type: "start-next", id: first.id, minutes: 2 }, 102000);
  expect(earnedPosition(s, first.mountainId)).toBe(7);
  s = transition(s, { type: "complete" }, 103000);
  expect(earnedPosition(s, first.mountainId)).toBe(0);
  s = transition(s, { type: "undo", id: s.completions[1].id }, 104000);
  expect(earnedPosition(s, first.mountainId)).toBe(7);
  expect(earnedPosition(s, crypto.randomUUID())).toBeNull();
  expect(checkpointPosition(0)).toEqual([18, 43]);
  expect(checkpointPosition(1)).toEqual([20, 40]);
  expect(checkpointPosition(13)).toEqual(checkpointPosition(2));
  expect(climberPosition(0)).toEqual([200, 218]);
  expect(climberPosition(1)[1]).toBeLessThan(climberPosition(0)[1]);
});
it("resumes saved next work without resetting it and rejects expired or archived targets without selecting", () => {
  let s = transition(emptySnapshot(), { type: "create", title: "Fictional guide", finishCondition: "Checked", action: "Draw", minutes: 2 }, 100000);
  const id = s.subtasks[0].id;
  s = transition(s, { type: "start-next", id, minutes: 2 }, 100000);
  s = transition(s, { type: "note", note: "Keep outline" }, 101000);
  s = transition(s, { type: "return-step", value: "Add edge" }, 101000);
  s = transition(s, { type: "save" }, 101000);
  const saved = currentSession(s)!;
  const resumed = transition(s, { type: "start-next", id, minutes: 12 }, 500000);
  expect(currentSession(resumed)).toMatchObject({ id: saved.id, remainingMs: saved.remainingMs, creditedMs: saved.creditedMs, note: saved.note, returnStep: saved.returnStep });
  s.sessions[0].remainingMs = 0;
  expect(transition(s, { type: "start-next", id, minutes: 2 }, 500000)).toBe(s);
  s.subtasks[0].archivedAt = new Date(500000).toISOString();
  expect(transition(s, { type: "start-next", id, minutes: 2 }, 500000)).toBe(s);
});
