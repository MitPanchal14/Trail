import { it, expect } from "vitest";
import { emptySnapshot, snapshotSchema, currentSession } from "../lib/domain";
import { transition, recoverSnapshot } from "../lib/actions";
it("migrates legacy notes, retains both return fields and never credits absence or saving", () => {
  const now = Date.now();
  let s = transition(emptySnapshot(now), { type: "create", title: "Fictional guide", finishCondition: "One checked page", action: "Sketch a leaf", minutes: 2 }, now);
  s = transition(s, { type: "start", minutes: 2 }, now);
  s = transition(s, { type: "note", note: "Outline done" }, now);
  const legacy = JSON.parse(JSON.stringify(s)); delete legacy.sessions[0].returnStep;
  s = snapshotSchema.parse(legacy);
  expect(currentSession(s)?.note).toBe("Outline done");
  expect(currentSession(s)?.returnStep).toBe("");
  s = transition(s, { type: "return-step", value: "Draw three veins" }, now);
  const interrupted = recoverSnapshot(snapshotSchema.parse(JSON.parse(JSON.stringify(s))), now + 86400000);
  expect(currentSession(interrupted)?.returnStep).toBe("Draw three veins");
  expect(currentSession(interrupted)?.remainingMs).toBe(120000);
  expect(currentSession(interrupted)?.status).toBe("interrupted");
  s = transition(s, { type: "save" }, now + 1000);
  expect(s.completions).toHaveLength(0);
  s = recoverSnapshot(snapshotSchema.parse(JSON.parse(JSON.stringify(s))), now + 86400000);
  expect(currentSession(s)?.remainingMs).toBe(119000);
  expect(currentSession(s)?.returnStep).toBe("Draw three veins");
  s = transition(s, { type: "complete" }, now + 86400000);
  const id = s.completions[0].id;
  s = transition(s, { type: "complete" }, now + 86400000);
  expect(s.completions).toHaveLength(1);
  s = transition(s, { type: "undo", id }, now + 86400000);
  expect(currentSession(s)?.status).toBe("saved");
  expect(currentSession(s)?.remainingMs).toBe(119000);
  expect(s.mountains[0].status).toBe("active");
});
