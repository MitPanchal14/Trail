import { test, expect } from "@playwright/test";
import { emptySnapshot } from "../lib/domain";
import { newDraft } from "../lib/planning";
import { transition } from "../lib/actions";
test("empty and meaningful creation drafts close and recover without clutter", async ({ page }, info) => {
  const s = emptySnapshot(); s.creationDraft = newDraft();
  await page.addInitScript((raw) => {
    if (!localStorage.getItem("work-trail:snapshot:v1")) localStorage.setItem("work-trail:snapshot:v1", raw);
  }, JSON.stringify(s));
  await page.goto("/");
  const continuation = page.getByRole("button", { name: "Continue creation draft", exact: true });
  await expect(continuation).toHaveCount(0);
  await page.getByRole("button", { name: "＋ New task", exact: true }).click();
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await expect(continuation).toHaveCount(0);
  await page.getByRole("button", { name: "＋ New task", exact: true }).click();
  await page.getByLabel("Describe the work").fill("   ");
  await page.getByRole("button", { name: "Write manually", exact: true }).click();
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await expect(continuation).toHaveCount(0);
  await page.getByRole("button", { name: "＋ New task", exact: true }).click();
  await page.getByLabel("Describe the work").fill("Fictional field guide");
  await page.getByText("Optional context", { exact: true }).click();
  await page.getByLabel("Where you are stuck", { exact: true }).fill("Need a first drawing");
  await page.getByRole("button", { name: "Write manually", exact: true }).click();
  await page.getByLabel("Mountain name", { exact: true }).fill("Leaf guide");
  await page.screenshot({ path: info.outputPath("creation.png"), fullPage: true });
  await page.getByRole("button", { name: "Close · keep draft", exact: true }).click();
  await page.reload(); await continuation.click();
  await expect(page.getByLabel("Describe the work")).toHaveValue("Fictional field guide");
  await expect(page.getByLabel("Mountain name", { exact: true })).toHaveValue("Leaf guide");
  await page.getByRole("button", { name: "Close · keep draft", exact: true }).click();
  await page.reload(); await continuation.click();
  await expect(page.getByLabel("Describe the work")).toHaveValue("Fictional field guide");
  // Context alone, then a manual review edit alone, must each count as work.
  await page.getByLabel("Describe the work").fill("");
  await page.getByLabel("Mountain name", { exact: true }).fill("");
  await page.getByRole("button", { name: "Close · keep draft", exact: true }).click();
  await page.reload(); await continuation.click();
  await page.getByText("Optional context", { exact: true }).click();
  await expect(page.getByLabel("Where you are stuck", { exact: true })).toHaveValue("Need a first drawing");
  await page.getByLabel("Where you are stuck", { exact: true }).fill("");
  await page.getByLabel("Mountain name", { exact: true }).fill("Manual-only review edit");
  await page.getByRole("button", { name: "Close · keep draft", exact: true }).click();
  await page.reload(); await continuation.click();
  await expect(page.getByLabel("Mountain name", { exact: true })).toHaveValue("Manual-only review edit");
});
test("normalized duplicate instructions stay hidden in Today and focus; distinct ones remain", async ({ page }, info) => {
  let s = transition(emptySnapshot(), { type: "create", title: "Fictional guide", finishCondition: "One checked page", action: "Sketch leaf", minutes: 10 });
  s.subtasks[0].nextAction = "  SKETCH   leaf ";
  s = transition(s, { type: "create", title: "Other guide", finishCondition: "One checked page", action: "Label leaf", minutes: 10 });
  s.subtasks[1].nextAction = "Write three labels next to the drawing.";
  await page.addInitScript((raw) => localStorage.setItem("work-trail:snapshot:v1", raw), JSON.stringify(s));
  await page.goto("/");
  await expect(page.locator(".next-instruction")).toBeVisible();
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await expect(page.locator(".next-instruction")).toHaveText("Write three labels next to the drawing.");
  await page.getByRole("button", { name: "Save my place", exact: true }).click();
  await page.getByText("Choose other work", { exact: true }).click();
  await page.getByRole("button", { name: /Sketch leaf.*Fictional guide/ }).click();
  await expect(page.locator(".next-instruction")).toHaveCount(0);
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await expect(page.locator(".next-instruction")).toHaveCount(0);
  await page.getByRole("button", { name: "Save my place", exact: true }).click();
  await page.getByRole("button", { name: "Plan today", exact: true }).click();
  await expect(page.getByLabel("What’s your day like?", { exact: true })).not.toBeVisible();
  await page.getByLabel("Time available today (optional)", { exact: true }).fill("30");
  await page.getByRole("checkbox", { name: /Sketch leaf —/ }).check();
  await expect(page.getByText("10 minutes suggested.", { exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath("planner.png"), fullPage: true });
  await page.getByLabel("Time available today (optional)", { exact: true }).focus();
  await expect(page.getByLabel("Time available today (optional)", { exact: true })).toBeFocused();
  await page.locator(".day-capacity summary").press("Enter");
  await page.getByLabel("What’s your day like?", { exact: true }).fill("Busy afternoon; about 30 minutes free.");
  await page.evaluate(() => { document.body.style.fontSize = "30px"; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
