import { test, expect } from '@playwright/test';
import { emptySnapshot } from '../lib/domain';
import { transition } from '../lib/actions';
test('review Undo earlier action after advancing', async ({page}, info) => {
 let s = transition(emptySnapshot(), {type:'create',title:'Fictional field guide',finishCondition:'Reviewed guide',action:'Draw outline',minutes:3});
 const first=s.subtasks[0].id;
 s.subtasks.push({...s.subtasks[0],id:crypto.randomUUID(),title:'Label drawing',nextAction:'Add labels',checkpointSlot:1,orderKey:1});
 s.mountains[0].nextCheckpointSlot=2;
 s=transition(s,{type:'start',minutes:3});
 s=transition(s,{type:'complete'});
  await page.addInitScript(raw=>{if (!localStorage.getItem('work-trail:snapshot:v1')) localStorage.setItem('work-trail:snapshot:v1',raw)},JSON.stringify(s));
 await page.goto('/');
 await page.getByRole('button',{name:'Start this action',exact:true}).click();
 await page.getByRole('button',{name:'Save my place',exact:true}).click();
 const journal=page.getByRole('region',{name:'Recorded checkpoint details'});
 await journal.locator('summary').click();
 await journal.getByRole('button',{name:'Undo completion',exact:true}).click();
 const state=await page.evaluate(()=>JSON.parse(localStorage.getItem('work-trail:snapshot:v1')!));
 expect(state.completions[0].undoneAt).toBeTruthy();
 expect(state.sessions.find((x:any)=>x.subtaskId===first).status).toBe('saved');
 expect(state.selection.selectedSubtaskId).not.toBe(first);
  await expect(page.getByRole('region', {name:'Undo recovery'})).toContainText('Draw outline reopened');
 await page.screenshot({path:info.outputPath('after-undo.png'),fullPage:true});
  const second = state.sessions[1];
  await page.getByRole('region', {name:'Undo recovery'}).getByRole('button',{name:'Return to Draw outline',exact:true}).click();
  await expect(page.locator('#action-title')).toBeFocused();
  expect((await page.evaluate(()=>JSON.parse(localStorage.getItem('work-trail:snapshot:v1')!))).sessions[1]).toEqual(second);
 await expect(page.getByRole('button',{name:'Resume',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Resume',exact:true}).click();
 await expect(page.getByRole('timer')).toBeVisible();
  await page.getByRole('button',{name:'Save my place',exact:true}).click();
  await page.reload();
  await page.locator('.correction-history summary').click();
  await expect(page.locator('.correction-history')).toContainText('Completion undone · action reopened');
 await page.getByRole('button',{name:'Plan today',exact:true}).click();
 await page.locator('.check-label').first().click();
 await page.screenshot({path:info.outputPath('planner.png'),fullPage:true});
});
