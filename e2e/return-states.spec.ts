import { test, expect } from "@playwright/test";
import { emptySnapshot } from "../lib/domain";
import { transition } from "../lib/actions";
test("ready, working, campsite, return context, earned light and Undo", async ({ page }, info) => {
  const s = transition(emptySnapshot(), { type: "create", title: "Fictional nature guide", finishCondition: "One reviewed page", action: "Sketch a leaf", minutes: 2 });
  await page.addInitScript((raw) => { if (!localStorage.getItem("work-trail:snapshot:v1")) localStorage.setItem("work-trail:snapshot:v1", raw); }, JSON.stringify(s));
  await page.route("**/api/plan", route => route.fulfill({ status: 503, json: { error: "AI disabled in tests" } }));
  await page.goto("/");
  await expect(page.getByText(/Destination: checkpoint 1/)).toBeVisible();
  await expect(page.getByRole("button", { name: "Start", exact: true })).toBeEnabled();
  await page.screenshot({ path: info.outputPath("ready.png"), fullPage: true });
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await expect(page.locator("canvas")).toHaveAttribute("data-state", "working");
  await page.screenshot({ path: info.outputPath("working.png"), fullPage: true });
  await page.getByText("Return note (optional)", { exact: true }).click();
  await page.getByLabel("Where I stopped").fill("Outline is ready");
  await page.getByLabel("First thing when I return").fill("Draw three veins");
  await page.getByRole("button", { name: "Save my place", exact: true }).click();
  await page.reload();
  await expect(page.getByText("Draw three veins", { exact: true })).toBeVisible();
  await expect(page.getByText("Outline is ready", { exact: true })).toBeVisible();
  await expect(page.locator("canvas")).toHaveAttribute("data-state", "saved");
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeEnabled();
  await expect(page.getByText("○ No checkpoints yet", { exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath("saved.png"), fullPage: true });
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await page.getByRole("button", { name: "Complete action", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Sketch a leaf earned checkpoint 1" })).toBeVisible();
  await expect(page.locator("canvas")).toHaveAttribute("data-state", "completed");
  await page.waitForTimeout(950); // Bounded reveal only; no timer credit is asserted from this wait.
  await page.screenshot({ path: info.outputPath("completed.png"), fullPage: true });
  const finalScene = await page.locator("canvas").evaluate((el: HTMLCanvasElement) => el.toDataURL());
  await page.reload();
  await expect(page.locator("canvas")).toHaveAttribute("data-state", "completed");
  await expect.poll(() => page.locator("canvas").evaluate((el: HTMLCanvasElement) => el.toDataURL())).toBe(finalScene);
  await page.getByRole("button", { name: "Undo completion", exact: true }).first().click();
  await expect(page.locator("canvas")).toHaveAttribute("data-state", "saved");
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
test("legacy interrupted notes recover under reduced motion and save needs no fields", async ({ page }) => {
  const now = Date.now();
  let s = transition(emptySnapshot(now), { type: "create", title: "Fictional notes", finishCondition: "Checked paragraph", action: "Write one example", minutes: 2 }, now);
  s = transition(s, { type: "start", minutes: 2 }, now);
  s = transition(s, { type: "note", note: "Legacy outline ready" }, now);
  const legacy = JSON.parse(JSON.stringify(s)); delete legacy.sessions[0].returnStep;
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.addInitScript((raw) => { if (!localStorage.getItem("work-trail:snapshot:v1")) localStorage.setItem("work-trail:snapshot:v1", raw); }, JSON.stringify(legacy));
  await page.goto("/");
  await expect(page.getByText("Legacy outline ready", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Write one example", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  const canvas = page.locator("canvas");
  const staticScene = await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL());
  await page.waitForTimeout(300);
  expect(await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())).toBe(staticScene);
  await page.getByRole("button", { name: "Save my place", exact: true }).click();
  await expect(page.getByText("○ No checkpoints yet", { exact: true })).toBeVisible();
});
