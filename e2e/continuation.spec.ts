import { test, expect } from "@playwright/test";
import { emptySnapshot, dateKey } from "../lib/domain";
import { transition } from "../lib/actions";
import { newDraft } from "../lib/planning";
test("three accepted actions continue, retain return context and earn visible ascent", async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await page.getByRole("button", { name: "＋ New task", exact: true }).click();
  await page.getByLabel("Describe the work").fill("Fictional leaf guide");
  await page.getByRole("button", { name: "Write manually", exact: true }).click();
  await page.getByLabel("Mountain name", { exact: true }).fill("Fictional leaf guide");
  await page.getByLabel("Finish condition", { exact: true }).fill("Three checked drawings");
  for (let i = 1; i <= 3; i++) {
    if (i > 1) await page.getByRole("button", { name: "+ Add another action", exact: true }).click();
    await page.getByLabel(`Action ${i} title`, { exact: true }).fill(`Draw leaf ${i}`);
    await page.getByLabel(`Action ${i} instruction`, { exact: true }).fill(`Outline specimen ${i}`);
    await page.getByLabel(`Action ${i} session minutes`, { exact: true }).fill(String(i * 3));
  }
  await page.getByLabel("I reviewed the goal, finish condition and every action").check();
  await page.getByRole("button", { name: "Accept breakdown", exact: true }).click();
  let canvas = page.locator("canvas");
  const before = await canvas.getAttribute("data-position");
  await canvas.screenshot({ path: info.outputPath("before-first.png") });
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await expect(canvas).toHaveAttribute("data-position", before!);
  await page.getByRole("button", { name: "Complete action", exact: true }).click();
  await expect(canvas).not.toHaveAttribute("data-position", before!);
  const one = await canvas.getAttribute("data-position");
  await canvas.screenshot({ path: info.outputPath("after-first.png") });
  await expect(page.getByText("1 / 3 accepted actions completed", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Draw leaf 2", exact: true })).toBeVisible();
  await page.getByLabel("Next session length", { exact: true }).fill("7");
  await page.screenshot({ path: info.outputPath("continuation.png"), fullPage: true });
  await page.getByRole("button", { name: "Start next action", exact: true }).click();
  await expect(page.getByRole("timer")).toHaveText(/0[67]:/);
  await expect(canvas).toHaveAttribute("data-position", one!);
  await page.getByText("Return note (optional)", { exact: true }).click();
  await page.getByLabel("Where I stopped").fill("Outline ready");
  await page.getByLabel("First thing when I return").fill("Add veins");
  await page.getByRole("button", { name: "Save my place", exact: true }).click();
  const records = () => page.evaluate(() => JSON.parse(localStorage.getItem("work-trail:snapshot:v1")!));
  const saved = (await records()).sessions[1];
  const reopened = await page.context().newPage();
  await page.close();
  page = reopened;
  canvas = page.locator("canvas");
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Add veins", exact: true })).toBeVisible();
  expect((await records()).sessions[1]).toEqual(saved);
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeEnabled();
  await page.screenshot({ path: info.outputPath("saved-return.png"), fullPage: true });
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await page.getByRole("button", { name: "Complete action", exact: true }).click();
  await expect(canvas).not.toHaveAttribute("data-position", one!);
  await canvas.screenshot({ path: info.outputPath("after-second.png") });
  const two = await canvas.evaluate((c: HTMLCanvasElement) => c.toDataURL());
  await page.reload();
  await expect.poll(() => canvas.evaluate((c: HTMLCanvasElement) => c.toDataURL())).toBe(two);
  await page.getByRole("button", { name: "Undo completion", exact: true }).first().click();
  await expect(canvas).toHaveAttribute("data-position", one!);
  expect((await records()).completions.filter((c: { undoneAt: string | null }) => !c.undoneAt)).toHaveLength(1);
  await page.getByRole("button", { name: "Edit breakdown", exact: true }).click();
  await page.getByRole("button", { name: "Close · keep draft", exact: true }).click();
  await page.getByRole("button", { name: "Edit breakdown", exact: true }).click();
  await expect(page.getByLabel("Mountain name", { exact: true })).toHaveValue("Fictional leaf guide");
});

for (const context of ["new", "other", "same"] as const) {
  test(`draft ownership: ${context} draft is named and retained`, async ({ page }) => {
    let s = transition(emptySnapshot(), { type: "create", title: "Fictional mountain A", finishCondition: "Checked", action: "Draw A", minutes: 3 });
    const a = s.selection.selectedSubtaskId!;
    s = transition(s, { type: "create", title: "Fictional mountain B", finishCondition: "Checked", action: "Draw B", minutes: 5 });
    const b = s.selection.selectedMountainId!;
    s = transition(s, { type: "select", id: a });
    s.creationDraft = { ...newDraft(), description: "Retained fictional draft", goal: "Retained name", editingMountainId: context === "new" ? null : context === "same" ? s.selection.selectedMountainId : b };
    await page.addInitScript(raw => { if (!localStorage.getItem("work-trail:snapshot:v1")) localStorage.setItem("work-trail:snapshot:v1", raw); }, JSON.stringify(s));
    await page.goto("/");
    await page.getByRole("button", { name: "Edit breakdown", exact: true }).click();
    if (context === "same") {
      await expect(page.getByLabel("Mountain name", { exact: true })).toHaveValue("Retained name");
      return;
    }
    const choice = page.getByRole("dialog", { name: "Keep your existing draft?" });
    await expect(choice).toContainText(context === "new" ? "new-project draft" : "Fictional mountain B");
    await choice.press("Escape");
    await page.reload();
    await page.getByRole("button", { name: "Edit breakdown", exact: true }).click();
    await page.getByRole("button", { name: "Resume existing draft", exact: true }).click();
    if (context === "new") await expect(page.getByLabel("Describe the work")).toHaveValue("Retained fictional draft");
    else await expect(page.getByLabel("Mountain name", { exact: true })).toHaveValue("Retained name");
    await page.getByRole("button", { name: "Close · keep draft", exact: true }).click();
    await page.getByRole("button", { name: "Edit breakdown", exact: true }).click();
    await page.getByRole("button", { name: "Keep draft and cancel edit", exact: true }).click();
    await page.getByRole("button", { name: "Edit breakdown", exact: true }).click();
    page.once("dialog", d => d.accept());
    await page.getByRole("button", { name: "Discard draft and edit this mountain", exact: true }).click();
    await expect(page.getByLabel("Mountain name", { exact: true })).toHaveValue("Fictional mountain A");
  });
}

test("saved next work resumes unchanged; deferred choice, rejected writes and final counts stay honest", async ({ page }) => {
  let s = transition(emptySnapshot(), { type: "create", title: "Fictional two-part study", finishCondition: "Reviewed", action: "First", minutes: 3 });
  const first = s.subtasks[0];
  const second = { ...first, id: crypto.randomUUID(), title: "Second", nextAction: "Check specimen", orderKey: 1, checkpointSlot: 13, suggestedMinutes: 8 };
  s.subtasks.push(second); s.mountains[0].nextCheckpointSlot = 14;
  s = transition(s, { type: "start-next", id: second.id, minutes: 8 });
  s = transition(s, { type: "note", note: "Keep the reference" });
  s = transition(s, { type: "return-step", value: "Check the edge" });
  s = transition(s, { type: "save" });
  s.dayPlans.push({ dateKey: dateKey(Date.now(), s.calendarTimeZone), availabilityText: "", availableMinutes: null, draftSubtaskIds: [], committedAt: new Date().toISOString(), commitments: [{ id: crypto.randomUUID(), subtaskId: second.id, titleSnapshot: second.title, committedAt: new Date().toISOString(), disposition: "deferred", dispositionAt: new Date().toISOString() }] });
  await page.addInitScript(raw => { if (!localStorage.getItem("work-trail:snapshot:v1")) localStorage.setItem("work-trail:snapshot:v1", raw); }, JSON.stringify(s));
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await page.getByText("Choose other work", { exact: true }).click();
  await page.getByRole("button", { name: /^First Fictional two-part study/ }).click();
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await page.getByRole("button", { name: "Complete action", exact: true }).click();
  const resume = page.getByRole("button", { name: "Resume next action", exact: true });
  await expect(resume).toBeDisabled();
  await expect(page.getByText("Where I stopped: Keep the reference", { exact: true })).toBeVisible();
  await page.getByRole("checkbox", { name: /Work on this deferred action now/ }).check();
  await expect(resume).toBeEnabled();
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw Error("Fictional storage failure"); }; });
  await resume.click();
  await expect(page.getByText(/Not saved to this browser/).first()).toBeVisible();
  await expect(resume).toBeDisabled();
  await page.reload();
  // Recovery deliberately prioritizes the saved action; this is still explicit Resume.
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Second", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Complete action", exact: true }).click();
  await expect(page.getByRole("heading", { name: "All planned steps complete", exact: true }).first()).toBeVisible();
  await expect(page.getByText("2 / 2 accepted actions completed", { exact: true })).toBeVisible();
  await expect(page.locator("canvas")).toHaveAttribute("data-segment", "1");
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem("work-trail:snapshot:v1")!));
  expect(stored.mountains[0].status).toBe("active");
  expect(stored.dayPlans[0].commitments[0].disposition).toBe("deferred");
});
