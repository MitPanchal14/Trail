import { test, expect } from "@playwright/test";
import { emptySnapshot } from "../lib/domain";
import { transition } from "../lib/actions";

for (const width of [1280, 390, 320]) test(`visible return and explicit continuation at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 844 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  let s = transition(emptySnapshot(), { type: "create", title: "Fictional specimen guide", finishCondition: "Two reviewed illustrations", action: "Draw outline", minutes: 3 });
  s.subtasks.push({ ...s.subtasks[0], id: crypto.randomUUID(), title: "Label veins", nextAction: "Add three labels to the drawing", checkpointSlot: 1, orderKey: 1 });
  s.mountains[0].nextCheckpointSlot = 2;
  s = transition(s, { type: "start", minutes: 3 });
  await page.addInitScript(raw => {
    if (!localStorage.getItem("work-trail:snapshot:v1")) localStorage.setItem("work-trail:snapshot:v1", raw);
  }, JSON.stringify(s));
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem("work-trail:snapshot:v1")!));
  const noOverflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto("/");
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await expect(page.getByLabel("Where I stopped")).toBeVisible();
  await expect(page.getByLabel("First thing when I return")).toBeVisible();
  await page.getByLabel("Where I stopped").fill("Outline ready for review");
  await page.getByLabel("First thing when I return").fill("Check the leaf edge");
  await page.getByRole("button", { name: "Save my place", exact: true }).click();
  const saved = (await read()).sessions[0];
  await page.reload();
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeEnabled();
  await expect(page.getByRole("heading", { name: "Check the leaf edge", exact: true })).toBeVisible();
  await expect(page.getByText("Outline ready for review", { exact: true })).toBeVisible();
  expect((await read()).sessions[0]).toEqual(saved);
  expect((await read()).completions).toHaveLength(0);
  await noOverflow();
  await page.screenshot({ path: info.outputPath(`saved-${width}.png`), fullPage: true });
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Check the leaf edge", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Complete action", exact: true }).click();
  const position = await page.locator("canvas").getAttribute("data-position");
  await expect(page.locator(".just-completed")).toContainText("Draw outline");
  await expect(page.getByText("Up next · Action 2 of 2", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Label veins", exact: true })).toBeVisible();
  await expect(page.getByText("1 / 2 accepted actions completed", { exact: true })).toBeVisible();
  expect((await read()).sessions).toHaveLength(1);
  await page.getByLabel("Next session length", { exact: true }).fill("4");
  await noOverflow();
  await page.screenshot({ path: info.outputPath(`next-${width}.png`), fullPage: true });
  await page.getByRole("button", { name: "Start this action", exact: true }).click();
  await expect(page.getByRole("timer")).toHaveText(/0[34]:/);
  await page.getByRole("button", { name: "Complete action", exact: true }).click();
  await expect(page.getByRole("button", { name: "Start this action", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Confirm goal complete", exact: true })).toBeVisible();
  expect((await read()).summitConfirmations).toHaveLength(0);
  await page.getByRole("button", { name: "Undo completion", exact: true }).first().click();
  await expect(page.getByText("1 / 2 accepted actions completed", { exact: true })).toBeVisible();
  await expect(page.locator("canvas")).toHaveAttribute("data-position", position!);
  await noOverflow();
});
