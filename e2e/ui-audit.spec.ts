import { test, expect } from "@playwright/test";
import { emptySnapshot } from "../lib/domain";
import { transition } from "../lib/actions";

test("saved hierarchy, compact world, planner prerequisites and measured interface contrast", async ({ page }, info) => {
  if (info.project.name === "desktop") await page.setViewportSize({ width: 1360, height: 900 });
  let s = transition(emptySnapshot(), { type: "create", title: "Fictional field guide", finishCondition: "One reviewed page", action: "Sketch the leaf", minutes: 10 });
  s = transition(s, { type: "start", minutes: 10 });
  s = transition(s, { type: "save" });
  await page.addInitScript(raw => { if (!localStorage.getItem("work-trail:snapshot:v1")) localStorage.setItem("work-trail:snapshot:v1", raw); }, JSON.stringify(s));
  await page.route("**/api/plan", route => route.fulfill({ status: 503, json: { error: { message: "AI disabled in this test" } } }));
  await page.goto("/");
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeEnabled();
  const action = page.locator(".real-action");
  await expect(action.getByText("Sketch the leaf", { exact: true })).toHaveCount(1);
  await expect(action.getByText(/No note saved/)).toHaveCount(0);
  await expect(action.getByText(/Recorded session time/)).not.toBeVisible();
  await expect(page.locator("canvas")).toHaveCount(1);
  await page.screenshot({ path: info.outputPath("today.png"), fullPage: true });
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await page.getByLabel("First thing when I return").fill("Add the three branching veins before checking the illustration against the fictional reference specimen");
  const note = "The outline and stem are ready. Keep the annotated reference beside the drawing. ".repeat(6);
  await page.getByLabel("Where I stopped").fill(note);
  await page.getByRole("button", { name: "Save my place", exact: true }).click();
  await expect(action.locator(".next-instruction")).toContainText("Add the three branching veins");
  await action.getByText("Read full stopping note", { exact: true }).click();
  await expect(action.getByText(note.trim(), { exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath("today-long-notes.png"), fullPage: true });
  await page.getByRole("button", { name: "Plan today", exact: true }).click();
  const commit = page.getByRole("button", { name: "Commit today’s plan", exact: true });
  await expect(commit).toBeDisabled();
  await expect(page.getByText(/Choose work to continue/)).toBeVisible();
  await expect(page.getByRole("button", { name: "Suggest a plan with AI", exact: true })).toBeDisabled();
  await page.screenshot({ path: info.outputPath("planner-empty.png"), fullPage: true });
  await page.getByLabel("Time available today (optional)", { exact: true }).fill("30");
  await page.getByRole("checkbox", { name: /Sketch the leaf —/ }).check();
  await expect(commit).toBeEnabled();
  await expect(page.getByText("10 minutes suggested.", { exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath("planner.png"), fullPage: true });
  const contrast = await page.evaluate(() => {
    const rgb = (v: string) => v.match(/[\d.]+/g)!.slice(0, 3).map(Number);
    const lum = (v: string) => rgb(v).map(c => { c /= 255; return c <= .04045 ? c / 12.92 : ((c + .055) / 1.055) ** 2.4; }).reduce((a, c, i) => a + c * [.2126, .7152, .0722][i], 0);
    const ratio = (a: string, b: string) => (Math.max(lum(a), lum(b)) + .05) / (Math.min(lum(a), lum(b)) + .05);
    return ["body", ".real-action h2", ".context p", ".primary:not(:disabled)", ".secondary:not(:disabled)", ".day-minutes input", ".world-footer"].map(selector => {
      const el = document.querySelector(selector)!;
      let parent: Element | null = el;
      while (parent && getComputedStyle(parent).backgroundColor === "rgba(0, 0, 0, 0)") parent = parent.parentElement;
      const css = getComputedStyle(el), bg = getComputedStyle(parent!).backgroundColor;
      return { selector, text: ratio(css.color, bg), boundary: css.borderStyle === "solid" ? ratio(css.borderColor, bg) : null };
    });
  });
  await info.attach("measured-contrast", { body: JSON.stringify(contrast, null, 2), contentType: "application/json" });
  console.log("Audit contrast", contrast);
  for (const result of contrast) expect(result.text).toBeGreaterThanOrEqual(4.5);
  for (const result of contrast.filter(r => r.boundary !== null)) expect(result.boundary).toBeGreaterThanOrEqual(3);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await commit.click();
  await page.getByRole("button", { name: "＋ New task", exact: true }).click();
  await expect(page.getByRole("button", { name: "Discard draft", exact: true })).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("creation.png"), fullPage: true });
  await page.getByLabel("Describe the work").fill("Fictional bark study");
  await page.getByRole("button", { name: "Close · keep draft", exact: true }).click();
  await page.reload();
  await page.getByRole("button", { name: "Continue creation draft", exact: true }).click();
  await expect(page.getByLabel("Describe the work")).toHaveValue("Fictional bark study");
});

test("creation remains reachable in a short viewport with keyboard and reduced motion", async ({ page }, info) => {
  await page.setViewportSize({ width: info.project.name === "mobile" ? 390 : 720, height: 480 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await page.getByRole("button", { name: "＋ New task", exact: true }).click();
  await page.getByRole("button", { name: "Write manually", exact: true }).click();
  await page.getByLabel("Mountain name", { exact: true }).fill("Fictional bark study");
  await page.getByLabel("Finish condition", { exact: true }).fill("One checked page");
  await page.getByLabel("Action 1 title", { exact: true }).fill("Draw one pattern");
  await page.getByLabel("Action 1 instruction", { exact: true }).fill("Draw three short lines");
  const accept = page.getByRole("button", { name: "Accept breakdown", exact: true });
  await accept.focus();
  await expect(accept).toBeInViewport();
  await page.screenshot({ path: info.outputPath("creation-short.png"), fullPage: true });
  await accept.press("Enter");
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await page.getByRole("button", { name: "Save my place", exact: true }).click();
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeEnabled();
});
